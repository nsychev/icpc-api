COUNTRIES: tuple[Country, ...] = tuple(
    Country(
        id=id_,
        version=0,
        a2=a2,
        a3=a3,
        number=number,
        currency=currency,
        name=name,
        available=available,
        uuid=uuid,
    )
    for id_, a2, a3, number, currency, name, available, uuid in _ROWS
)

_BY_KEY = {key.strip().casefold(): c for c in COUNTRIES for key in (c.a2, c.a3, c.name) if key}


def country(key: str) -> Country:
    """Look a country up by ISO alpha-2 (``UZ``), alpha-3 (``UZB``) or name."""
    try:
        return _BY_KEY[key.strip().casefold()]
    except KeyError:
        raise ValueError(
            f"unknown country {key!r}; use an ISO code such as UZ, or the name"
        ) from None
